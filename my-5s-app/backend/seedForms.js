async function seedData() {
    try {
        await mongoose.connect(process.env.MONGO_URI || 'mongodb://localhost:27017/green7s');
        console.log('✅ เชื่อมต่อ MongoDB สำเร็จ');

        // ลบแบบฟอร์มเก่าออกก่อนลงแบบฟอร์มใหม่
        await FormTemplate.deleteMany({});
        console.log('🗑️ ล้างแบบฟอร์มเดิมเรียบร้อยแล้ว');

        // บันทึกแบบฟอร์มตั้งต้นใหม่
        await FormTemplate.insertMany(defaultForms);
        console.log('🎉 บันทึกแบบฟอร์มมาตรฐาน Green 7S Plus ทั้งหมด 10 หมวดเข้าสู่ DB เรียบร้อยแล้ว!');

        mongoose.connection.close();
    } catch (err) {
        console.error('❌ เกิดข้อผิดพลาดในการ Seed Data:', err);
        mongoose.connection.close();
    }
}

